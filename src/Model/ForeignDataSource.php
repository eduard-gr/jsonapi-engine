<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Model;

/**
 * Чужой источник данных: читает и пишет своим кодом, таблицы движок не знает. Пара к `DatabaseEntitySource`
 * (источник в базе, SQL строит движок); оба — виды `DataSource`.
 *
 * Наследник объявляет табличную структуру, как любой `DataSource` (константы колонок и `COLUMNS`), а операции —
 * методами экземпляра через интерфейсы: чтение — `SelectForeignDataInterface`, запись —
 * `InsertForeignDataInterface`, `UpdateForeignDataInterface`, `DeleteForeignDataInterface` (все здесь же, в
 * `src/Model`). Реализованный интерфейс — знак, что операция поддержана. Объект источника создаёт
 * контейнер зависимостей приложения (PSR-11), сборщик дерева берёт его по имени класса. Где на самом деле лежат данные (файл, сервис, та же база
 * через собственный SQL), движку неизвестно и безразлично.
 *
 * Ограничения, которые из этого следуют:
 *  - может быть только моделью целиком: в соединении (`Join`) лист обязан быть `DatabaseEntitySource`;
 *  - SQL у него нет: `ModelTree::getFrom()` бросает `LogicException`, `ModelTree::getRootEntity()` возвращает null;
 *  - условий родителя он не получает (цепочка предков на нём обрывается) — только условия клиента;
 *  - транзакции движка на него не действуют: что источник записал, откат базы не вернёт (если только источник сам
 *    не пишет через то же подключение);
 *  - полная замена детей связи и родитель вложенного маршрута для него не планируются (`LogicException` в
 *    `Plan\Write\WritePlanner`); аргументы маршрута приходят в каждый метод источника как есть.
 */
abstract class ForeignDataSource extends DataSource {}
