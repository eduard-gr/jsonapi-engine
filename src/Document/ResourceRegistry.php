<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Document;

use Ds\Map;

/**
 * Реестр ресурсов одного выполнения дерева: каждый ресурс по ключу "type:id" — в одном экземпляре.
 *
 * Один экземпляр на выполнение. Его получают все RegisterIterator дерева и Document:
 *  - RegisterIterator (над каждым сериализатором) регистрирует каждый построенный ресурс через intern() и отдаёт дальше
 *    зарегистрированный объект. Повторный type:id (например, провайдер, выбранный JOIN-ом
 *    в строку каждого своего сертификата) даёт тот же объект, поэтому дубли не создаются вовсе;
 *  - Document при сборке included находит через find() ресурсы, на которые ссылаются связи.
 *
 * Реестр держит все ресурсы, построенные за выполнение, — в том числе те, на которые никто не ссылается
 * (провайдеры справочника PreloadIterator без сертификатов в ответе: в документ они не попадают, до них нельзя
 * дойти по связям). Поэтому память
 * растёт со всем прочитанным, а не только с документом.
 *
 * При повторной регистрации того же type:id остаётся первый объект: атрибуты повторного
 * молча теряются. Пока каждый ресурс строится из одного запроса, его копии одинаковы.
 *
 * Реестр не переиспользуется между выполнениями: intern() вернул бы объекты прошлого выполнения
 * с их атрибутами, и свежие данные из базы молча потерялись бы. Кроме того, связи, которые
 * в новом выполнении никто не перезапишет, остались бы от прошлого.
 * Для каждого выполнения дерева — новый реестр, как и новое дерево.
 *
 * Хранилище — Ds\Map, а не массив: ключи "type:id" — строки, и на них Ds\Map примерно
 * на 10% компактнее (измерено: ~59 байт на элемент против ~65 у массива при 10 000 ключей).
 */
final class ResourceRegistry
{
    /**
     * @var Map<string, ResourceRecord> Ключ "type:id" => ресурс
     */
    private Map $records;

    public function __construct()
    {
        $this->records = new Map();
    }

    /**
     * Возвращает зарегистрированный ресурс с тем же type:id, а если такого нет —
     * регистрирует $record и возвращает его же.
     *
     * Вызывающий должен дальше работать с возвращённым объектом, а не с $record:
     * при повторе это другой объект, и связи, записанные $record, никуда не попадут
     */
    public function intern(ResourceRecord $record): ResourceRecord
    {
        $key = $record->key();
        $registered = $this->records->get($key, null);

        if ($registered !== null) {
            return $registered;
        }

        $this->records->put($key, $record);

        return $record;
    }

    /**
     * Ресурс по ключу "type:id" или null, если такой не регистрировался
     * (например, связь есть, а сам ресурс не загружали)
     */
    public function find(string $key): ?ResourceRecord
    {
        return $this->records->get($key, null);
    }
}
