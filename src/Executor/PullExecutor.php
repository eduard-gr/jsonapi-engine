<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Executor;

use Generator;
use IteratorAggregate;

/**
 * Контракт pull-узла дерева исполнителя: узел — это источник потока, родитель сам тянет из него элементы,
 * и getIterator() всегда возвращает Generator. Реализуют исполнители выборки (`Executor\Select\…Iterator`).
 *
 * Модель выполнения задаёт интерфейс, а не операция: pull — PullExecutor (данные идут снизу вверх),
 * push — PushExecutor (данные приходят сверху, узел пишет их в базу). Оба лежат в корне Executor, общие для всех
 * операций. Классы называются существительным по роли и модели: `…Iterator` у pull-узлов, `…Writer` у push-узлов;
 * операция — в подпапке и префиксе (`Insert…Writer`, позже `Update…Writer`, `Delete…Writer`).
 *
 * Executor — слой выполнения (pull-дерево выборки — по модели итераторов Volcano): узлы держат состояние (генераторы, PDO,
 * реестр) и выполняют дерево. Описание плана, которое строит и переписывает планировщик, — отдельный
 * слой Plan: неизменяемые узлы без состояния. Дерево итераторов строит по плану IteratorBuilder перед каждым
 * выполнением; example/document.php и DocumentTreeTest собирают его руками.
 *
 * IteratorAggregate::getIterator() обещает только Traversable; здесь тип возврата сужен
 * до Generator (PHP это разрешает). Поэтому узлы, которые читают потоки вручную через
 * valid()/current()/next(), получают генератор гарантированно — это проверяет сам язык
 * при объявлении класса, и проверки instanceof Generator при выполнении не нужны.
 *
 * Узлы принимают на вход PullExecutor, а не произвольный Traversable: в дерево можно подставить
 * только другой узел.
 *
 * Что именно течёт по потоку (строки array или ресурсы ResourceRecord),
 * интерфейс не различает — это описано строкой «Поток: вход → выход» в описании каждого узла
 * и в @return его getIterator(). Подключать можно только узлы, у которых выход одного
 * совпадает со входом другого; язык этого пока не проверяет, ошибка проявится при выполнении.
 * Исключение — выход узлов соединения: его отмечает интерфейс JoinIterator (всегда ResourceRecord).
 *
 * Повторный проход контракт не обещает: часть узлов одноразовые (SharedDataIterator,
 * SharedRowJoinIterator — их генераторы создаются в конструкторе), поэтому дерево, в котором
 * они есть, выполняется только один раз. Повторный getIterator() корня не выбросит ошибку,
 * а молча вернёт пустой поток.
 *
 * Топология: explain() описывает узел и всё поддерево под ним, не выполняя его. Им можно
 * посмотреть собранное дерево при отладке и сравнить его с ожидаемым в тестах.
 * В отличие от getIterator(), explain() можно вызывать сколько угодно раз — и до, и во время,
 * и после выполнения, — в том числе у одноразовых узлов: описание от этого не меняется.
 *
 * Для отладки дерева нужен именно explain(): var_dump() и print_r() узла показывают его
 * внутренние свойства (генераторы, PDO), по которым топологию не восстановить —
 * генератор не показывает, какой узел за ним стоит. Дерево они, как и explain(), не выполняют.
 *
 * @extends IteratorAggregate<int, mixed>
 */
interface PullExecutor extends IteratorAggregate
{
    #[\Override]
    public function getIterator(): Generator;

    /**
     * Описание узла и его поддерева: тип узла, параметры и описания дочерних узлов
     * под именами параметров конструктора (source, outer, inner, data).
     *
     * Ничего не выполняет: не запускает генераторы и не читает источники, поэтому
     * вызывать можно в любой момент, в том числе посреди выполнения дерева.
     *
     * Узел, который читают несколько потребителей (SharedDataIterator), описывается
     * у каждого из них заново: в описании он встретится столько раз, сколько у него потребителей.
     *
     * Ключи соединения и сортировки описываются своими именами ('id', 'certificate_id'),
     * ресурс SerializeIterator — классом ресурса.
     *
     * @return array<string, mixed> Ключ 'node' — класс узла, остальные — его параметры
     */
    public function explain(): array;
}
