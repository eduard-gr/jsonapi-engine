<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Executor\Select;

use Generator;
use Ggs\JsonApiEngine\Executor\PullExecutor;

/**
 * Раздаёт одну и ту же строку источника нескольким потребителям.
 *
 * Поток: вход — строки array (обычно SqlScanIterator) → выход — строки array, отдельное окно
 * на каждого потребителя (обычно SerializeIterator).
 *
 * Проблема: из одной строки селекта строится несколько ресурсов (certificate, detail и delivery),
 * то есть один поток данных читают сразу несколько SerializeIterator. Генератор можно пройти
 * только один раз, и если отдать его напрямую двум foreach, каждый из них будет вызывать
 * next() и забирать строки у другого: потребители получат разные строки, а часть строк
 * будет пропущена. Кроме того, потребитель, подключившийся после того как поток уже сдвинулся,
 * упадёт на rewind() с исключением "Cannot rewind a generator that was already run".
 *
 * Решение: каждый потребитель получает из getIterator() собственный генератор-«окно»
 * на общий источник. Окно отдаёт строку, на которой сейчас стоит источник, и само его
 * не сдвигает: шаг потребителя возвращает его в окно, и если источник не сдвинулся,
 * потребитель снова получит ту же строку. Перематывать общий генератор не нужно —
 * у каждого потребителя своё окно.
 *
 * Сдвиг делается в одном месте — в SharedScanIterator через advance(),
 * один раз за такт, после того как все потребители обработали текущую строку.
 * Ресурсы, построенные ветвями из одной строки, соединяет SharedRowJoinIterator.
 *
 * Семейство узлов работает только вместе: SharedDataIterator (общий источник),
 * SharedRowJoinIterator (соединение ветвей) и SharedScanIterator (сдвиг источника).
 *
 * advance() — единственный способ сдвинуть источник, сам генератор источника наружу
 * не выдаётся.
 *
 * В отличие от tee с буфером, строки нигде не накапливаются: в памяти одна текущая строка.
 *
 * Ограничения:
 *  - каждый потребитель должен прочитать ровно одну строку за такт, иначе потоки разъедутся;
 *  - потребители должны быть ленивыми (генераторы) и двигаться синхронно с SharedScanIterator;
 *  - узел одноразовый: генератор источника создаётся в конструкторе и не перематывается.
 *    После того как источник прочитан до конца, новые окна сразу пусты.
 *    Узел-источник при этом хранится отдельно, поэтому explain() работает всегда.
 *
 * В explain() узел встречается столько раз, сколько у него потребителей (все SerializeIterator
 * ветвей и SharedScanIterator): описание дерева не отслеживает общие узлы.
 */
class SharedDataIterator implements PullExecutor
{
    /**
     * Узел-источник — только для explain(): генератор не показывает, какой узел за ним стоит
     */
    private readonly PullExecutor $node;

    /**
     * Общий источник. Сдвигается только через advance().
     * Приватный, чтобы потребители не могли вызвать у генератора next(), send() или throw()
     */
    private readonly Generator $source;

    /**
     * @param PullExecutor $source Источник строк, обычно SqlScanIterator
     */
    public function __construct(
        PullExecutor $source,
    )
    {
        $this->node = $source;
        $this->source = $source->getIterator();
    }

    /**
     * Описывает узел-источник, а не генератор: генератор не трогается, источник не сдвигается
     */
    #[\Override]
    public function explain(): array
    {
        return [
            'node' => static::class,
            'source' => $this->node->explain(),
        ];
    }

    /**
     * Окно потребителя на общий источник: отдаёт текущую строку и не сдвигает источник.
     * Каждый вызов создаёт новое окно, поэтому потребителей может быть сколько угодно.
     *
     * Окно заканчивается, когда источник становится невалидным (после последнего advance()).
     *
     * @return Generator<int, array<string, mixed>>
     */
    #[\Override]
    public function getIterator(): Generator
    {
        // Первый valid() запускает генератор источника (выполняет запрос)
        while ($this->source->valid()) {
            // Шаг потребителя возвращает сюда; если SharedScanIterator не сдвинул источник,
            // потребитель снова получит ту же строку
            yield $this->source->current();
        }
    }

    /**
     * Переходит к следующей строке общего источника.
     *
     * Вызывает только SharedScanIterator, после того как все ветви дерева обработали текущую строку.
     * Потребители (SerializeIterator) вызывать его не должны: их собственные шаги источник
     * не сдвигают, для этого и нужны окна.
     *
     * Метод публичный, потому что в PHP нельзя открыть метод только одному классу.
     * Ограничение «только SharedScanIterator» — договорённость, а не защита на уровне языка:
     * вызов из потребителя сдвинет строку для всех ветвей, и они разъедутся.
     *
     * Перед первой строкой вызывать не нужно: генератор запускается первым valid().
     * После последней строки valid() вернёт false, и окна потребителей завершатся.
     * Повторный вызов на закончившемся источнике ничего не делает.
     */
    public function advance(): void
    {
        $this->source->next();
    }

    /**
     * Есть ли у источника текущая строка. Первый вызов запускает генератор источника
     * (выполняет запрос). SharedScanIterator по нему проверяет, что поддерево не закончилось
     * раньше источника
     */
    public function valid(): bool
    {
        return $this->source->valid();
    }
}
