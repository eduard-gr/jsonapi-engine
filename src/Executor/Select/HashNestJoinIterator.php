<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Executor\Select;

use Ds\Map;
use Generator;
use Ggs\JsonApiEngine\Document\ResourceRecord;
use Ggs\JsonApiEngine\Executor\PullExecutor;
use UnexpectedValueException;

/**
 * Соединяет главные ресурсы со связанными по ключу и записывает связь to-many (1:N).
 *
 * Название: nest join — соединение из реляционной алгебры для вложенных данных. Обычное
 * соединение отдаёт плоские пары (главный, связанный), а nest join — каждый главный один раз,
 * с вложенным в него списком всех связанных (возможно, пустым). Здесь этот список — связь
 * relationships[$name]. Hash — механизм: хеш-таблица по главным ресурсам.
 * Ту же семантику даёт MergeNestJoinIterator, но слиянием отсортированных потоков, без хеш-таблицы.
 *
 * Поток: вход — $outer: ResourceRecord (SharedScanIterator, SerializeIterator, PreloadIterator
 * или другой узел соединения),
 * $inner: ?ResourceRecord (SerializeIterator или другой узел соединения)
 * → выход — ResourceRecord главного.
 *
 * В отличие от SharedRowJoinIterator, потоки не обязаны идти синхронно и приходить
 * из одного селекта: связанные ресурсы обычно читаются отдельным запросом (например,
 * домены сертификатов), и их количество не совпадает с количеством главных.
 *
 * Роли сторон. Имена $outer/$inner сохранены, но в этом узле они НЕ совпадают с классическими
 * ролями hash join, где build-сторону часто называют inner:
 *  - $outer — основное дерево (главные ресурсы, например certificate) — это build-сторона,
 *    она целиком кладётся в хеш-таблицу;
 *  - $inner — связанные ресурсы (например domain) — это probe-сторона, она читается построчно.
 *
 * Почему кешируется основное дерево: в JSON:API главные ресурсы обычно ограничены страницей,
 * а связанных больше, и они растут быстрее (домены, логи доменов). В хеш-таблицу кладётся
 * меньшая сторона. К тому же главные ресурсы всё равно до конца выполнения лежат в реестре,
 * а таблица держит ссылки на те же объекты, поэтому памяти почти не добавляется.
 *
 * Работает в две фазы:
 *  - build: $outer читается целиком в хеш-таблицу Ds\Map «ключ => главный ресурс»;
 *    каждому главному ресурсу сразу записывается пустая связь relationships[$name].data = [];
 *  - probe: $inner читается построчно, каждый связанный ресурс за O(1) находит своего
 *    главного по ключу и дописывается в его связь.
 * Главные ресурсы отдаются наружу только после probe: список связанных полон лишь в конце.
 *
 * Узел только записывает связи: сами связанные ресурсы никуда не копируются, в included
 * их соберёт Document по связям. Если $inner — другой узел соединения, связи связанных
 * ресурсов (например, логи домена) уже записаны им, и Document дойдёт по ним дальше.
 *
 * Семантика LEFT JOIN: главный ресурс без совпадений не пропадает, а остаётся с пустой связью
 * relationships[$name].data = [] — так JSON:API обозначает пустую to-many связь.
 *
 * Связанный ресурс, для которого нет главного, — LogicException: дочерний SQL повторяет условия
 * родителя (цепочка предков, Plan\Select\SharedScanNode::withSelect()), поэтому связанный без главного —
 * ошибка плана, а не данных. Поток, собранный не планировщиком, обязан соблюдать то же правило.
 *
 * Ключи соединения задаются именами $outer_key и $inner_key, а значения узел берёт
 * через ResourceRecord::getKey() (например, 'id' главного и 'certificate_id' связанного).
 * Имена, а не замыкания: дерево может собирать планировщик, а explain() показывает сами имена.
 * Поэтому внешний ключ должен быть в служебных ключах (keys) связанного ресурса, а не в attributes —
 * так он не попадает в JSON. Ключа с таким именем у ресурса нет — OutOfBoundsException.
 *
 * Ключи соединения — только целые числа, как и служебные ключи ResourceRecord.
 * Ключ главного ресурса должен быть уникальным в $outer, иначе — исключение.
 *
 * Вложенные соединения: любая сторона может быть другим узлом (не только листом).
 *  - $outer — например, PreloadIterator: сертификаты со связью provider и загруженным справочником;
 *  - $inner — например, HashNestJoinIterator или MergeNestJoinIterator. Для certificate ← domains ← logs
 *    внутренний узел записывает доменам связь logs и отдаёт домены, а этот узел записывает
 *    домены в связь сертификата. Порядок выхода внутреннего узла HashNestJoinIterator не важен —
 *    поэтому над MergeNestJoinIterator, который отдаёт домены по возрастанию id,
 *    а не certificate_id, стоит именно он.
 *
 * Порядок: главные ресурсы выходят в порядке $outer, связанные внутри связи — в порядке $inner.
 *
 * Гарантия для планировщика: $outer читается целиком и до конца (build завершается) раньше,
 * чем запрашивается первый элемент $inner. Поэтому, если обе стороны читают запросы
 * на одном подключении, их курсоры никогда не открыты одновременно: build дочитывает $outer
 * до конца, генератор SqlScanIterator завершается и закрывает курсор до того, как открывается
 * курсор $inner. Это позволяет ставить обе стороны на одно подключение даже
 * в небуферизованном режиме MySQL, где два открытых курсора на одном подключении запрещены.
 *
 * Гарантия держится, только пока курсор $inner не открыт до вызова getIterator() этого узла,
 * то есть $inner не читал никто другой раньше.
 *
 * Для вложенных соединений: если $outer — не лист (узел соединения или PreloadIterator), build
 * дочитывает до конца и его, поэтому закрываются все курсоры этой стороны (например,
 * сертификаты и справочник у PreloadIterator). Внутренний узел $inner начинает читаться только
 * после build, поэтому курсоры $outer к тому моменту уже закрыты. Дальше всё зависит от внутреннего
 * узла: HashNestJoinIterator тоже читает свои стороны по очереди (курсоры строго друг за другом),
 * а MergeNestJoinIterator держит оба своих курсора открытыми одновременно. Для дерева
 * (certificate + provider) ← (domains ← logs) с PreloadIterator в $outer и MergeNestJoinIterator в $inner
 * курсоры идут так: сертификаты, затем провайдеры (каждый закрывается до следующего),
 * затем домены и логи открыты вместе.
 *
 * Ограничения:
 *  - вся сторона $outer держится в хеш-таблице (в Ds\Map — почему не в массиве, см. build()),
 *    поэтому туда ставится меньшая сторона;
 *  - узел блокирующий: первый главный ресурс выходит только после того, как прочитаны
 *    обе стороны целиком, а при вложенных соединениях — все запросы всех уровней.
 *
 * Для связи N:1 (у главного один ресурс справочника, у справочника много главных) этот узел
 * не подходит: такую связь пишет сериализатор главного из внешнего ключа своей строки,
 * а справочник загружает PreloadIterator.
 */
class HashNestJoinIterator implements JoinIterator
{
    /**
     * @param PullExecutor $outer Поток главных ResourceRecord — build-сторона, кешируется целиком
     * @param PullExecutor $inner Поток связанных ?ResourceRecord — probe-сторона,
     *        читается построчно; элементы null пропускаются
     * @param string $outer_key Имя ключа соединения главного ресурса (ResourceRecord::getKey()),
     *        обычно 'id'; значение уникально в $outer
     * @param string $inner_key Имя ключа соединения связанного ресурса — служебный ключ
     *        с внешним ключом, например 'certificate_id'
     * @param string $name Имя связи в relationships главного ресурса
     */
    public function __construct(
        private PullExecutor    $outer,
        private PullExecutor    $inner,
        private string  $outer_key,
        private string  $inner_key,
        private string  $name,
    ) {}

    #[\Override]
    public function explain(): array
    {
        return [
            'node' => static::class,
            'name' => $this->name,
            'outer_key' => $this->outer_key,
            'inner_key' => $this->inner_key,
            'outer' => $this->outer->explain(),
            'inner' => $this->inner->explain(),
        ];
    }

    /**
     * @return Generator<int, ResourceRecord>
     * @throws UnexpectedValueException если ключ главного ресурса встретился в $outer дважды
     * @throws \LogicException если у связанного ресурса нет главного
     */
    #[\Override]
    public function getIterator(): Generator
    {
        $table = $this->build();

        foreach ($this->inner as $related) {
            if ($related === null) {
                continue;
            }

            $key = $related->getKey($this->inner_key);
            $parent = $table->get($key, null);

            // Нет главного ресурса с таким ключом — ошибка плана: дочерний SQL повторяет условия родителя
            // (цепочка предков), поэтому каждый связанный ресурс обязан найти своего главного
            if ($parent === null) {
                throw new \LogicException(
                    "Related resource {$related->key()} has no parent with key {$key} in HashNestJoinIterator '{$this->name}'"
                );
            }

            $parent->addRelationship(
                name: $this->name,
                related: $related
            );
        }

        // Ключи таблицы не нужны наружу; Ds\Map сохраняет порядок вставки, то есть порядок $outer
        yield from $table->values();
    }

    /**
     * Читает $outer целиком в хеш-таблицу «ключ => главный ресурс» и записывает каждому
     * главному ресурсу пустую связь — она останется пустой, если связанных не найдётся.
     *
     * Читает $outer до конца — на этом держится гарантия, что курсоры $outer и $inner
     * не открыты одновременно (см. описание класса)
     *
     * Таблица — Ds\Map, а не массив: ключи (id главных ресурсов) ожидаются разреженными,
     * и на них Ds\Map примерно на 10% компактнее (~36 байт на элемент против ~40 у массива).
     * Если ключи плотные и идут по возрастанию (1, 2, 3, …), PHP хранил бы массив в компактном
     * режиме packed array (~16 байт на элемент) — там массив был бы вдвое выгоднее.
     *
     * @return Map<int, ResourceRecord>
     * @throws UnexpectedValueException если ключ главного ресурса встретился дважды
     */
    private function build(): Map
    {
        $table = new Map();

        foreach ($this->outer as $record) {
            $key = $record->getKey($this->outer_key);

            // Иначе второй главный ресурс молча вытеснил бы первый из таблицы,
            // и первый ушёл бы наружу без связанных ресурсов
            if ($table->hasKey($key)) {
                throw new UnexpectedValueException("Duplicate outer key {$key} in HashNestJoinIterator '{$this->name}'");
            }

            $record->setRelationships(name: $this->name, related: []);
            $table->put($key, $record);
        }

        return $table;
    }
}
