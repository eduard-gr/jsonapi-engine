<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Executor\Select;

use Generator;
use Ggs\JsonApiEngine\Document\ResourceRecord;
use Ggs\JsonApiEngine\Executor\PullExecutor;

/**
 * Пропускает поток главных ресурсов, а после него загружает ресурсы справочника в реестр.
 *
 * Поток: вход — $source: ResourceRecord (главные ресурсы), $preload: ?ResourceRecord
 * (обычно SerializeIterator справочника) → выход — $source без изменений.
 *
 * Связь N:1 на ресурс справочника (например, provider сертификата) пишет сам сериализатор
 * главного ресурса из внешнего ключа своей строки — без соединения. Этот узел связи не трогает:
 * когда $source закончился, он вычитывает $preload до конца, а SerializeIterator справочника
 * регистрирует каждый ресурс в ResourceRegistry. Так Document при сборке included найдёт ресурсы,
 * на которые ссылаются связи.
 *
 * Почему справочник читается после $source, а не до. Справочник нужен не потоку, а только
 * Document при обходе связей, а обход начинается, когда поток прочитан целиком. Поэтому:
 *  - узел не блокирует: первый главный ресурс выходит сразу, не дожидаясь справочника
 *    (это заметно под MergeNestJoinIterator; HashNestJoinIterator всё равно ждёт весь $outer);
 *  - к моменту чтения справочника уже известно, на какие его ресурсы ссылаются главные —
 *    это задел для чтения справочника только по нужным id (WHERE id IN (...)) вместо целиком.
 * Имя Preload — о Document: справочник загружается в реестр заранее, до обхода связей,
 * а не до потока главных ресурсов.
 *
 * Узел нужен только ради included (в терминах JSON:API — include=provider). Без него связи
 * у главных ресурсов остаются, а самих ресурсов справочника в документе нет.
 *
 * Ресурс справочника — один объект в реестре, и Document добавит его в included один раз,
 * сколько бы главных на него ни ссылалось. Ресурсы, на которые никто не сослался, в реестре есть,
 * но в included не попадают: Document не дойдёт до них по связям.
 *
 * Битый внешний ключ (ссылка на ресурс, которого в справочнике нет) остаётся ссылкой:
 * в relationships — {id, type} несуществующего ресурса, в included — ничего. Узел это не проверяет.
 *
 * Чем отличается от узлов соединения: он не порождает свой поток, а пропускает $source как есть,
 * поэтому JoinIterator не реализует — $source может прийти и не от соединения (например,
 * от SharedScanIterator). Порядок $source сохраняется, поэтому узел можно ставить
 * в $outer MergeNestJoinIterator.
 *
 * Место в дереве: обычно сразу над потоком главных ресурсов (например, над SharedScanIterator
 * сертификатов), а сам он — $outer следующего соединения (HashNestJoinIterator с доменами).
 *
 * Гарантия для планировщика: $preload начинает читаться только после того, как $source прочитан
 * до конца — к этому моменту генераторы $source завершились и закрыли свои курсоры. Поэтому
 * курсоры $source и $preload на одном подключении не открыты одновременно. Но если узел стоит
 * в $outer MergeNestJoinIterator, справочник откроется, пока курсор $inner этого слияния ещё открыт:
 * MergeNestJoinIterator и так требует одновременных курсоров (см. его описание).
 *
 * Ограничения — все ошибки молчаливые, узел их не обнаруживает:
 *  - $source должен быть прочитан до конца: код после yield from выполняется, только когда
 *    потребитель запросит элемент после последнего. Если потребитель остановится раньше
 *    (break, частичное чтение), справочник не загрузится, и included молча останется без него.
 *    Сейчас все потребители дочитывают поток до конца: build() HashNestJoinIterator, проход
 *    MergeNestJoinIterator по $outer и Document. LIMIT поэтому задаётся в SQL-запросе данных,
 *    а не узлом, обрывающим поток; узел, который читает поток не до конца, над PreloadIterator
 *    ставить нельзя;
 *  - $preload должен регистрировать ресурсы в том же реестре, то есть состоять из SerializeIterator
 *    с тем же ResourceRegistry. Поток, который ресурсы не регистрирует (например, голый
 *    SqlScanIterator), будет прочитан впустую, и included останется без справочника;
 *  - тип ресурсов справочника должен совпадать с типом в ссылке сериализатора (например,
 *    'provider' и там и там), иначе Document не найдёт их по ключу "type:id".
 *
 * Память: весь справочник попадает в реестр, в том числе ресурсы, на которые никто
 * не сослался. Если справочник большой, а в выдаче используется малая его часть, лучше
 * сузить запрос справочника (WHERE id IN (...)).
 *
 * Повтор type:id в справочнике не обнаруживается: ResourceRegistry::intern() молча оставит
 * первый экземпляр.
 */
class PreloadIterator implements PullExecutor
{
    /**
     * @param PullExecutor $source Поток главных ResourceRecord — пропускается без изменений
     * @param PullExecutor $preload Поток ресурсов справочника ?ResourceRecord — вычитывается целиком
     *        после $source; должен регистрировать ресурсы в реестре документа (SerializeIterator)
     */
    public function __construct(
        private PullExecutor $source,
        private PullExecutor $preload,
    ) {}

    #[\Override]
    public function explain(): array
    {
        return [
            'node' => static::class,
            'source' => $this->source->explain(),
            'preload' => $this->preload->explain(),
        ];
    }

    /**
     * @return Generator<int, ResourceRecord> То же, что отдаёт $source
     */
    #[\Override]
    public function getIterator(): Generator
    {
        yield from $this->source;

        // Сюда доходим, только если потребитель дочитал $source до конца (см. ограничения),
        // и до обхода связей в Document: справочник к нему уже в реестре.
        // Сами элементы не нужны: в реестр их кладёт SerializeIterator, здесь справочник только
        // вычитывается до конца. Курсоры $source к этому моменту уже закрыты
        foreach ($this->preload as $ignored_record) {
        }
    }
}
