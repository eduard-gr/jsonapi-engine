<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Resource;

use Ggs\JsonApiEngine\Document\ResourceRecord;

/**
 * Ручная сериализация: ресурс сам собирает себя из строки запроса. Реализуют наследники `Resource`; пара —
 * `DeserializeInterface` (запись).
 *
 * Интерфейс и есть признак: ресурс его реализует — значит, поддерживает операцию. `Executor\Select\ReaderBuilder`
 * смотрит на класс ресурса из плана и ставит для такого ресурса `ManualSerializeReader` вместо `SerializeReader`.
 * Метод `serialize()` без интерфейса никто не вызовет (`Resource::validate()` считает это ошибкой).
 *
 * Зачем: тип или набор атрибутов ресурса зависит от строки (полиморфный ресурс), свой формат значения, составной
 * атрибут (`columns`) — по описанию `ATTRIBUTES` он не собирается, ресурс с ним обязан реализовать интерфейс.
 *
 * Метод вызывается на экземпляре ресурса из контейнера зависимостей: ему доступны зависимости конструктора. Один
 * объект служит всем строкам — состояние между вызовами хранить нельзя.
 */
interface SerializeInterface
{
    /**
     * Ресурс из строки. Контракт вызова — в описании `Executor\Select\ManualSerializeReader`.
     *
     * На методе целиком: id, type, атрибуты и связи по внешнему ключу. Что запросил клиент, говорит `$fields`:
     * выводить надо только названное в нём и в его порядке. По наличию колонки в `$tuple` об этом судить нельзя —
     * колонка бывает в строке и как ключ соединения или колонка из `getRequiredColumns()`. Колонки, нужные всегда,
     * ресурс называет в `getRequiredColumns()`. Ключи соединений в `ResourceRecord` дописывает читатель.
     *
     * Контекст вызова передаётся отдельными аргументами (решение 2026-11-20: без объекта контекста, пока не станет
     * видно, насколько это удобно). То, что относится к запросу или приложению (пользователь, локаль, сервисы),
     * ресурс получает через конструктор из контейнера зависимостей.
     *
     * @param array<string, mixed> $tuple колонка модели → значение, как пришло из источника: первичный ключ (не
     *                                    NULL), колонки атрибутов `fields`, колонки `getRequiredColumns()`, ключи
     *                                    соединений
     * @param list<string>         $fields запрошенные атрибуты и связи по внешнему ключу (имена в API), в порядке
     *                                     запроса — как в узле плана; один и тот же список для всех строк
     * @return ResourceRecord|null null — ресурса в строке нет
     */
    public function serialize(array $tuple, array $fields): ?ResourceRecord;
}
