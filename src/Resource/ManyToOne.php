namespace Ggs\JsonApiEngine\Resource;

/**
 * Связь «многие к одному»: у строки владельца не больше одной строки ресурса, а у строки ресурса может быть много
 * владельцев (у сертификата один провайдер, у провайдера много сертификатов).
 *
 * Ключ лежит на стороне владельца: `relation` — `[внешний ключ владельца, первичный ключ ресурса]`.
 * Пример: `certificate.provider` — `[provider_id, id]`, `certificates.provider_id = providers.id`.
 * `Resource::validate()` не проверяет, что колонка ресурса — его первичный ключ: при другой колонке связь
 * описана неверно, но ошибки не будет.
 *
 * Поэтому это связь по внешнему ключу (`Resource::foreignRelationship()`): идентификатор связанного ресурса известен
 * из строки владельца без соединения, связь запрашивается в `fields`, как атрибут, и её пишет сериализация владельца
 * (`SerializeIterator` или ручной `serialize()`; внешний ключ `NULL` — пустая связь, `data: null`), а сам ресурс
 * нужен только для `included`.
 * Он читается отдельным SQL-запросом, и `PreloadIterator(source: поток владельца, preload: поток ресурса)` после
 * владельцев загружает ресурсы в `ResourceRegistry`; `Document` найдёт их по связи. Узел соединения не нужен.
 * В примере провайдеры — `QUERY4` (`example/document.php`).
 *
 * Строки владельца связь не размножает. Цепочки предков у запроса ресурса пока нет: ресурс считается небольшим
 * словарём и читается целиком (в included попадают только те, на кого ссылаются). Если она понадобится, шаг к
 * владельцам — `IN (подзапрос)`: у ресурса может быть много владельцев, и `JOIN` размножил бы строки.
 */
