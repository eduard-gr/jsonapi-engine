<?php

declare(strict_types=1);

namespace Ggs\JsonApiEngine\Resource;

use Ggs\JsonApiEngine\Parser\Write\PersistentIdentity;

/**
 * Ручная десериализация: ресурс сам превращает данные операции записи в строку «колонка модели → значение».
 * Реализуют наследники `Resource`; пара — `SerializeInterface` (чтение).
 *
 * Интерфейс и есть признак: ресурс его реализует — значит, поддерживает операцию. `Executor\Write\WriterBuilder`
 * смотрит на класс ресурса из плана и даёт писателям такого ресурса (`InsertResourceWriter`, `UpdateResourceWriter`)
 * `ManualResourceDeserializer` вместо `ResourceDeserializer`. Метод `deserialize()` без интерфейса никто не вызовет
 * (`Resource::validate()` считает это ошибкой).
 *
 * Зачем: составной атрибут (`columns`) — по описанию `ATTRIBUTES` его значение по нескольким колонкам не разложить;
 * свой разбор значения перед записью. Разрешений интерфейс не даёт: можно ли ресурс создавать и менять, говорят
 * `InsertableInterface` и `UpdatableInterface`, а какие атрибуты присылать нельзя (`mode` READ) — проверяет парсер до вызова.
 *
 * Метод вызывается на экземпляре ресурса из контейнера зависимостей: ему доступны зависимости конструктора. Один
 * объект служит всем операциям — состояние между вызовами хранить нельзя.
 */
interface DeserializeInterface
{
    /**
     * Строка ресурса из данных операции. Контракт вызова — в описании
     * `Executor\Write\ManualResourceDeserializer`.
     *
     * На методе целиком: все присланные атрибуты и связи по внешнему ключу — общая раскладка по `ATTRIBUTES` для
     * этого ресурса не выполняется. В строку кладётся только присланное: присутствие колонки, а не значение,
     * решает, что её трогать (`null` — это NULL в колонку). Первичный ключ и колонки связи с родителем метод не
     * пишет: их добавляют писатели; `$id` и `$link` даны только для чтения.
     *
     * Контекст вызова передаётся отдельными аргументами (решение 2026-11-20: без объекта контекста, пока не станет
     * видно, насколько это удобно). То, что относится к запросу или приложению (пользователь, локаль, сервисы),
     * ресурс получает через конструктор из контейнера зависимостей.
     *
     * @param array<string, mixed>                   $attributes присланные атрибуты: имя в API → значение
     * @param array<string, PersistentIdentity|null> $references присланные связи по внешнему ключу: имя → цель,
     *                                                           null — связь очищается
     * @param bool                                   $is_insert  true — ресурс создаётся (`InsertOperation`), false —
     *                                                           изменяется (`UpdateOperation`)
     * @param int|null                               $id         id изменяемого ресурса; null при вставке — id даст
     *                                                           база
     * @param array<string, mixed>                   $link       колонки связи с родителем → значение
     *                                                           (`['certificate_id' => 1]`); пусто — родителя нет
     * @return array<string, mixed> колонка модели → значение; колонка не из модели ресурса — LogicException
     * @throws InvalidAttributeException если присланное значение атрибута разобрать нельзя: клиент получит 400
     *                                   с именем атрибута. Форму значения парсер не проверяет — это делает метод
     */
    public function deserialize(array $attributes, array $references, bool $is_insert, ?int $id, array $link): array;
}
