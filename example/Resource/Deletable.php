/**
 * Возможность ресурса: его можно удалять. Пара к `Resource\Insertable`; пока прототип — читает только
 * example/patch-document.php (`WriteDocumentParser`), при переносе записи в `src/` переезжает в `src/Resource/`.
 *
 * Маркер на классе ресурса, проверка — `is_a($class, Deletable::class, true)`. В PATCH нужен цели связи по владению,
 * когда документ может удалить её ресурсы: `meta.op: remove` у элемента, полная замена to-many (связь без пометок:
 * неназванные удаляются), замена to-one через `lid` или `null` (текущий удаляется). Проверка — по форме документа, а не
 * по данным: полная замена требует маркера, даже если удалять в итоге нечего. Без маркера — 403 с указателем.
 * Многие-ко-многим `unlink` удаляет строку связки, а не цель: это `Updatable` владельца.
 *
 * Корень `DELETE /…/{id}` — тоже `Deletable`. Потомков удаляет база (`ON DELETE CASCADE`: логи домена уходят с
 * доменом), их маркер не проверяется: `Deletable` значит «можно удалить запросом», а что уходит вместе с ресурсом,
 * задаёт схема базы.
 *
 * @temporary Временное место: интерфейс лежит в example/Resource/, потому что его реализуют ресурсы примера и ему
 *            нужна автозагрузка, а `src/` прототип не меняет. При переносе записи —
 *            `src/Resource/Deletable.php`, рядом с `Insertable` (`Ggs\JsonApiEngine\Resource\Deletable`).
 */
